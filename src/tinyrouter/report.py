"""``make report``: results/report.md and the README's generated block, from committed JSON.

No number in the README's first screen is typed by hand (docs/PLAN.md AC8).
Everything between ``BEGIN`` and ``END`` in README.md is rewritten from:
``results/analysis/{summary,haiku}.json``, ``results/llm/haiku-8way.json``,
``results/efficiency/*.json``, ``results/cost/cost.json``, the curve indexes,
the pilots and the run JSONs. ``--check`` rewrites nothing and exits 1 when
either file differs from what the JSON gives; tests/test_report.py runs the
same comparison in CI.
"""

